import {createDatabase} from '../lib/db.js';
import {writeFileSync} from 'node:fs';
const db=createDatabase(':memory:');
const quote=s=>'"'+s.replaceAll('"','""')+'"';
const tables=db.prepare("SELECT name,sql FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%' ORDER BY name").all();
const statements=[],constraints=[];
for(const table of tables){
 const columns=db.prepare(`PRAGMA table_info(${quote(table.name)})`).all();
 const primary=columns.filter(c=>c.pk).sort((a,b)=>a.pk-b.pk);
 const fields=columns.map(c=>{const type=c.type==='INTEGER'?'BIGINT':c.type==='REAL'?'DOUBLE PRECISION':'TEXT';let def=c.dflt_value;if(def==='CURRENT_TIMESTAMP')def="to_char(CURRENT_TIMESTAMP AT TIME ZONE 'UTC','YYYY-MM-DD HH24:MI:SS')";return `${quote(c.name)} ${type}${c.name==='id'&&c.pk&&c.type==='INTEGER'?' GENERATED BY DEFAULT AS IDENTITY':''}${c.notnull?' NOT NULL':''}${def!==null?' DEFAULT '+def:''}`;});
 if(primary.length)fields.push('PRIMARY KEY ('+primary.map(c=>quote(c.name)).join(',')+')');
 for(const i of db.prepare(`PRAGMA index_list(${quote(table.name)})`).all())if(i.unique&&i.origin!=='pk'){
  const cols=db.prepare(`PRAGMA index_info(${quote(i.name)})`).all().map(c=>quote(c.name));
  if(i.partial)statements.push(`CREATE UNIQUE INDEX ${quote(i.name)} ON ${quote(table.name)} (${cols.join(',')}) WHERE "end" IS NULL;`);
  else fields.push('UNIQUE ('+cols.join(',')+')');
 }
 for(const check of table.sql.match(/CHECK\([^)]*\)/g)||[])fields.push(check);
 statements.unshift(`CREATE TABLE ${quote(table.name)} (\n  ${fields.join(',\n  ')}\n);`);
 for(const fk of db.prepare(`PRAGMA foreign_key_list(${quote(table.name)})`).all())constraints.push(`ALTER TABLE ${quote(table.name)} ADD CONSTRAINT ${quote(table.name+'_'+fk.from+'_fk')} FOREIGN KEY (${quote(fk.from)}) REFERENCES ${quote(fk.table)} (${quote(fk.to)});`);
}
const sql=statements.join('\n\n')+'\n\n'+constraints.join('\n')+'\n';
writeFileSync(new URL('../lib/postgres-schema.js',import.meta.url),'// Initial PostgreSQL schema generated from the clinic SQLite schema.\nexport const postgresSchema = '+JSON.stringify(sql)+';\n');
console.log(`Generated ${tables.length} tables with foreign keys and unique constraints`);db.close();
